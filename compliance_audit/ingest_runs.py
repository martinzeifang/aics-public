"""Hintergrundläufe des Framework-Einlesens — Zustand und Historie (#2022).

WARUM ÜBERHAUPT
``POST /api/compliance-audit/frameworks/<fw>/ingest`` lief **synchron im
Request**. Gemessen am 09.11.2026: Das BSI-Verzeichnis (3 PDFs, 10,7 MB)
braucht **3 668 s** für 976 Abschnitte, der AI Act 305 s, die DSGVO 180 s. Das
Frontend gab nach 300 s auf („timeout of 300000ms exceeded"), und der Server
arbeitete weiter — der Anwender sah einen Fehler, und im Hintergrund entstand
ein Ergebnis, von dem er nichts erfuhr.

Ein größeres Zeitlimit ist die falsche Antwort: Es verschiebt die Grenze und
lässt den Browser eine Stunde auf eine Antwort warten, die ein Thread im
Server hält. Richtig ist, den Lauf vom Request zu lösen.

WARUM IN DER DATENBANK UND NICHT IM PROZESS
Die Installation fährt mehrere gunicorn-Worker. Ein Lauf, der in Worker A
startet, ist in einem Dict von Worker B nicht sichtbar — die Statusabfrage
landet per Zufall beim richtigen oder beim falschen. Dieselbe Überlegung wie
bei ``cra_sync_runs`` (#937), und dort hat sie sich bewährt.

Tabelle ``audit_ingest_runs`` (im Gutachten-Schema, wie der ganze
Audit-Bestand — historisch, #1713).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from shared import db as _sdb

#: Zustände eines Laufs. ``laeuft`` ist der einzige, der eine zweite Anforderung
#: für dasselbe Framework abweist (409) — zwei gleichzeitige Läufe über dasselbe
#: Verzeichnis schreiben dieselben Abschnitte doppelt.
ZUSTAENDE: tuple[str, ...] = ("laeuft", "fertig", "fehler", "abgebrochen")


def ensure_table(db_path: Path) -> None:
    con = _sdb.connect(str(db_path))
    try:
        con.execute(
            """CREATE TABLE IF NOT EXISTS audit_ingest_runs (
                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                   framework TEXT NOT NULL,
                   zustand TEXT NOT NULL DEFAULT 'laeuft',
                   gestartet_am TEXT DEFAULT (aics_now()),
                   beendet_am TEXT,
                   gestartet_von TEXT NOT NULL DEFAULT '',
                   abschnitte INTEGER NOT NULL DEFAULT 0,
                   dateien INTEGER NOT NULL DEFAULT 0,
                   fortschritt TEXT NOT NULL DEFAULT '',
                   log_json TEXT NOT NULL DEFAULT '[]'
               )""")
        con.execute("CREATE INDEX IF NOT EXISTS idx_audit_ingest_fw "
                    "ON audit_ingest_runs(framework, gestartet_am DESC)")
        con.commit()
    finally:
        con.close()


def laeuft(db_path: Path, framework: str) -> dict[str, Any] | None:
    """Der laufende Lauf dieses Frameworks — oder ``None``."""
    ensure_table(db_path)
    con = _sdb.connect(str(db_path))
    try:
        row = con.execute(
            "SELECT * FROM audit_ingest_runs WHERE framework=? AND zustand='laeuft' "
            "ORDER BY gestartet_am DESC LIMIT 1", (framework,)).fetchone()
        return _zeile(row) if row else None
    finally:
        con.close()


def starten(db_path: Path, framework: str, *, von: str = "",
            dateien: int = 0) -> int:
    ensure_table(db_path)
    con = _sdb.connect(str(db_path))
    try:
        cur = con.execute(
            "INSERT INTO audit_ingest_runs (framework, gestartet_von, dateien, "
            "fortschritt) VALUES (?,?,?,?)",
            (framework, von, int(dateien), "vorbereitet"))
        lauf_id = int(cur.lastrowid or 0)
        con.commit()
        return lauf_id
    finally:
        con.close()


def fortschritt(db_path: Path, lauf_id: int, text: str, *,
                abschnitte: int | None = None) -> None:
    """Zwischenstand festhalten — damit die Abfrage etwas zu zeigen hat.

    Ein Lauf über eine Stunde ohne jede Rückmeldung ist von einem hängenden
    nicht zu unterscheiden, und der Anwender bricht ab.
    """
    ensure_table(db_path)
    con = _sdb.connect(str(db_path))
    try:
        if abschnitte is None:
            con.execute("UPDATE audit_ingest_runs SET fortschritt=? WHERE id=?",
                        (text[:400], lauf_id))
        else:
            con.execute("UPDATE audit_ingest_runs SET fortschritt=?, abschnitte=? "
                        "WHERE id=?", (text[:400], int(abschnitte), lauf_id))
        con.commit()
    finally:
        con.close()


def beenden(db_path: Path, lauf_id: int, *, zustand: str, abschnitte: int = 0,
            log: list[str] | None = None) -> None:
    if zustand not in ZUSTAENDE:
        raise ValueError(f"Unbekannter Zustand: {zustand!r}")
    ensure_table(db_path)
    con = _sdb.connect(str(db_path))
    try:
        con.execute(
            "UPDATE audit_ingest_runs SET zustand=?, beendet_am=aics_now(), "
            "abschnitte=?, fortschritt=?, log_json=? WHERE id=?",
            (zustand, int(abschnitte), "", json.dumps(log or [], ensure_ascii=False),
             lauf_id))
        con.commit()
    finally:
        con.close()


def letzter(db_path: Path, framework: str) -> dict[str, Any] | None:
    ensure_table(db_path)
    con = _sdb.connect(str(db_path))
    try:
        row = con.execute(
            "SELECT * FROM audit_ingest_runs WHERE framework=? "
            "ORDER BY gestartet_am DESC LIMIT 1", (framework,)).fetchone()
        return _zeile(row) if row else None
    finally:
        con.close()


def historie(db_path: Path, framework: str = "", grenze: int = 20) -> list[dict[str, Any]]:
    ensure_table(db_path)
    con = _sdb.connect(str(db_path))
    try:
        if framework:
            rows = con.execute(
                "SELECT * FROM audit_ingest_runs WHERE framework=? "
                "ORDER BY gestartet_am DESC LIMIT ?", (framework, int(grenze))).fetchall()
        else:
            rows = con.execute(
                "SELECT * FROM audit_ingest_runs ORDER BY gestartet_am DESC LIMIT ?",
                (int(grenze),)).fetchall()
        return [_zeile(r) for r in rows]
    finally:
        con.close()


def _zeile(row: Any) -> dict[str, Any]:
    d = dict(row)
    try:
        d["log"] = json.loads(d.pop("log_json", "[]") or "[]")
    except Exception:  # noqa: BLE001
        d["log"] = []
    return d


__all__ = ["ZUSTAENDE", "ensure_table", "laeuft", "starten", "fortschritt",
           "beenden", "letzter", "historie"]
