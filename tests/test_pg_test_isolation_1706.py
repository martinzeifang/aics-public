"""Test-Isolation über Lauf-Grenzen hinweg (#1706).

Die Per-Test-Isolation leert bei aktivem ``AICS_TRACK_SCHEMAS`` nur die **berührten**
Schemata — aus Geschwindigkeit so gewollt (#1340). Zu Beginn eines Prozesses ist die
Liste jedoch leer, also überlebt alles, was ein vorheriger Lauf liegen gelassen hat.
Gegen eine dauerhafte Entwicklungs-Datenbank schlugen Tests dadurch je nach
Vorgeschichte fehl, etwa ``test_cra_vuln_sync_937`` mit ``assert 3 == 1``.

Beim Nachsehen kam ein zweites Problem zum Vorschein: Jeder Lauf legt **neue**
Wegwerf-Schemata an. Lokal hatten sich **1048 Schemata mit 7157 Tabellen**
angesammelt; ein TRUNCATE darüber sprengt ``max_locks_per_transaction``
(``out of shared memory``) — und diese Ausnahme wurde stillschweigend verschluckt.
Der Altbestand wuchs also unbemerkt, und die Bereinigung tat gar nichts.
"""
from __future__ import annotations

import pytest

from shared import db as sdb

pytestmark = pytest.mark.usefixtures('_postgres_session')


def _schema_mit_zeile(name: str) -> None:
    """Wegwerf-Schema mit einer Tabelle und einer Zeile anlegen."""
    pool = sdb.get_pool()
    conn = pool.getconn()
    try:
        with conn.cursor() as cur:
            cur.execute(f'CREATE SCHEMA IF NOT EXISTS "{name}"')          # nosec B608
            cur.execute(f'CREATE TABLE IF NOT EXISTS "{name}".spur '      # nosec B608
                        '(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v TEXT)')
            cur.execute(f'INSERT INTO "{name}".spur(v) VALUES (%s)', ('alt',))  # nosec B608
        conn.commit()
    finally:
        pool.putconn(conn)


def _zeilen(name: str) -> int | None:
    """Zeilenzahl, oder ``None`` wenn Schema/Tabelle fehlt."""
    pool = sdb.get_pool()
    conn = pool.getconn()
    try:
        with conn.cursor() as cur:
            try:
                cur.execute(f'SELECT count(*) FROM "{name}".spur')  # nosec B608
                n = cur.fetchone()[0]
                conn.commit()
                return n
            except Exception:
                conn.rollback()
                return None
    finally:
        pool.putconn(conn)


def _schema_existiert(name: str) -> bool:
    pool = sdb.get_pool()
    conn = pool.getconn()
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT 1 FROM information_schema.schemata "
                        "WHERE schema_name = %s", (name,))
            da = cur.fetchone() is not None
        conn.commit()
        return da
    finally:
        pool.putconn(conn)


# ── Sessionstart-Truncate ────────────────────────────────────────────────────

def test_truncate_leert_auch_unberuehrte_schemata():
    """Der Kern des Fehlers: Ein Schema, das dieser Prozess nie angefasst hat.

    Mit Tracking leert die Per-Test-Isolation nur Berührtes — ``alle_schemata=True``
    muss das Tracking übergehen, sonst bleibt Altbestand liegen.
    """
    name = 'pytest_iso_1706_unberuehrt'
    _schema_mit_zeile(name)
    # Tracking-Liste leeren: so sieht der Zustand bei Prozessstart aus.
    with sdb._touched_lock:
        sdb._touched_schemas.clear()

    assert _zeilen(name) == 1, 'Vorbedingung: Zeile liegt im Schema'
    sdb.drop_test_schemas(alle_schemata=True)
    assert _zeilen(name) == 0, 'Altbestand wurde nicht geleert'
    assert _schema_existiert(name), \
        'Truncate darf das Schema NICHT loeschen — sonst zahlt jede Testdatei die DDL neu'


def test_ohne_alle_schemata_bleibt_unberuehrtes_liegen():
    """Gegenprobe: Das Standardverhalten ist bewusst sparsam (#1340).

    Ohne diese Zusicherung wäre nicht belegt, dass das Flag überhaupt etwas tut.
    """
    if not sdb._track_schemas:
        pytest.skip('ohne AICS_TRACK_SCHEMAS gibt es den Unterschied nicht')
    name = 'pytest_iso_1706_sparsam'
    _schema_mit_zeile(name)
    with sdb._touched_lock:
        sdb._touched_schemas.clear()

    sdb.drop_test_schemas()          # ohne Flag
    assert _zeilen(name) == 1, 'ohne alle_schemata darf nichts Unberuehrtes geleert werden'
    sdb.drop_test_schemas(alle_schemata=True)   # aufräumen


# ── Hausmeister: Schemata löschen ────────────────────────────────────────────

def test_hausmeister_loescht_altschema(monkeypatch):
    """``drop_stale_test_schemas`` entfernt Wegwerf-Schemata dauerhaft.

    Die Keep-Liste wird so gesetzt, dass **nur** das Testschema zur Löschung
    freigegeben ist — sonst würde der Test der laufenden Session die Schemata
    wegräumen.
    """
    name = 'pytest_iso_1706_hausmeister'
    _schema_mit_zeile(name)
    assert _schema_existiert(name)

    pool = sdb.get_pool()
    conn = pool.getconn()
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT schema_name FROM information_schema.schemata")
            alle = {r[0] for r in cur.fetchall()}
        conn.commit()
    finally:
        pool.putconn(conn)
    monkeypatch.setattr(sdb, '_KEEP_SCHEMAS', alle - {name})

    n = sdb.drop_stale_test_schemas()
    assert n == 1, f'erwartet genau 1 geloeschtes Schema, waren {n}'
    assert not _schema_existiert(name), 'Schema wurde nicht geloescht'


def test_hausmeister_schuetzt_app_schemata(monkeypatch):
    """users/audit/scheduler/public dürfen nie gelöscht werden.

    Dort liegt der App-Zustand (Konten, Revisionsspur) — ein Verlust würde die
    Session unbrauchbar machen und wäre nicht wiederherstellbar.
    """
    assert {'public', 'users', 'audit', 'scheduler'} <= sdb._KEEP_SCHEMAS
    aufrufe: list[str] = []

    class FakeCur:
        def execute(self, sql, params=None):
            aufrufe.append(sql)
            self._sql = sql
        def fetchall(self):
            return []
        def fetchone(self):
            return (0,)
        def __enter__(self): return self
        def __exit__(self, *a): return False

    class FakeConn:
        def cursor(self): return FakeCur()
        def commit(self): pass
        def rollback(self): pass

    class FakePool:
        def getconn(self): return FakeConn()
        def putconn(self, c): pass

    monkeypatch.setattr(sdb, 'get_pool', lambda: FakePool())
    sdb.drop_stale_test_schemas()
    # Die Auswahlabfrage muss die Keep-Liste als Parameter nutzen, nicht alles nehmen.
    auswahl = [s for s in aufrufe if 'information_schema.schemata' in s]
    assert auswahl, 'keine Auswahlabfrage abgesetzt'
    assert 'schema_name <> ALL' in auswahl[0], \
        'Auswahl filtert die geschuetzten Schemata nicht heraus'
    assert not any('DROP SCHEMA' in s for s in aufrufe), \
        'ohne Kandidaten darf nichts geloescht werden'


def test_sessionstart_fixture_ist_autouse():
    """Strukturprüfung: Der Reset muss ohne Zutun jeder Testdatei greifen."""
    from pathlib import Path
    conftest = (Path(__file__).resolve().parent / 'conftest.py').read_text()
    assert '_pg_frischer_start' in conftest, 'Sessionstart-Fixture fehlt'
    block = conftest.split('def _pg_frischer_start', 1)[0]
    assert "scope='session', autouse=True" in block.rsplit('@pytest.fixture', 1)[-1], \
        'Sessionstart-Fixture ist nicht session-scoped autouse'
    assert 'drop_test_schemas(alle_schemata=True)' in conftest
    assert 'drop_stale_test_schemas' in conftest
